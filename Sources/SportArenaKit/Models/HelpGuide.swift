/// «Помощь»: what each part of the app is for, the same reference the site has under «Профиль → Помощь». The words follow the site's,
/// with the places that only exist on the web (a Telegram login, a keyboard shortcut) left out and the app's own controls named where the
/// site names its own.
public struct HelpSection: Equatable, Sendable, Identifiable {
    public struct Item: Equatable, Sendable, Identifiable {
        public let label: String
        public let text: String
        public var id: String { label }
    }

    public let id: String
    /// An SF Symbol.
    public let symbol: String
    public let title: String
    public let intro: String?
    public let items: [Item]

    init(id: String, symbol: String, title: String, intro: String? = nil, items: [(String, String)] = []) {
        self.id = id
        self.symbol = symbol
        self.title = title
        self.intro = intro
        self.items = items.map { Item(label: $0.0, text: $0.1) }
    }
}

