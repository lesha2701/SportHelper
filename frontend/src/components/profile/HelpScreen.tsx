export function HelpScreen({
  onBack,
  roles,
}: {
  onBack: () => void;
  roles?: { player: boolean; coach: boolean };
}) {
  const [showGuide, setShowGuide] = useState(false);

  return (
    <div className={profileStyles.screen}>
      <div className={profileStyles.card}>
        <TitleWithBack onBack={onBack}>
          <h1 className={profileStyles.pageHeading}>О приложении</h1>
        </TitleWithBack>
        <p className={profileStyles.subtitle}>
          SportArenaGlobal помогает находить тренеров, записываться на занятия и следить за тренировками и прогрессом.
          Ниже — что есть в каждом разделе.
        </p>
      </div>

      <div className={`${profileStyles.card} ${profileStyles.actionsCard}`}>
        <button type="button" className={profileStyles.buttonSecondary} onClick={() => setShowGuide(true)}>
          <Icon name="sparkles" size={16} />
          Как работает SportArenaGlobal
        </button>
        <p className={profileStyles.subtitle} style={{ margin: 0 }}>
          Короткое знакомство с приложением — можно пересмотреть в любой момент.
        </p>
      </div>

      {showGuide && <WelcomeGuide manual roles={roles} onFinish={() => setShowGuide(false)} />}

      {SECTIONS.filter((section) => TEAM_FEATURES_VISIBLE || section.title !== "Команды").map((section) => (
        <div className={profileStyles.card} key={section.title}>
          <h2 className={profileStyles.title} style={{ display: "flex", alignItems: "center", gap: 10 }}>
            <Icon name={section.icon} size={20} />
            {section.title}
          </h2>
          {section.intro && <p className={profileStyles.subtitle}>{section.intro}</p>}
          {section.items?.map((item) => (
            <div className={profileStyles.row} key={item.label}>
              <span className={profileStyles.rowLabel}>{item.label}</span>
              <span className={profileStyles.rowValue}>{capitalized(item.text)}</span>
            </div>
          ))}
        </div>
      ))}
    </div>
  );
}
