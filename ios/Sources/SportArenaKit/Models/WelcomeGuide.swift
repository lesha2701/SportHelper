import Foundation

/// «Знакомство с приложением»: a short tour of what the app does, the same one the site shows to a new person and from
/// «Настройки → Знакомство с приложением». The words follow the site's guide, with the places that only exist on the web left out.
public struct WelcomeStep: Equatable, Sendable, Identifiable {
    /// How a step draws its icons: tiles side by side, or arrows between them to show a sequence.
    public enum Layout: Equatable, Sendable { case tiles, flow, roles }

    public struct Tile: Equatable, Sendable {
        public let symbol: String
        public let label: String
    }

    public let id: String
    /// Who the step is for, above the title.
    public let kicker: String?
    public let title: String
    public let lead: String
    /// Short concrete things the person can do.
    public let points: [String]
    public let extra: String?
    public let layout: Layout
    public let tiles: [Tile]

    init(id: String, kicker: String? = nil, title: String, lead: String, points: [String] = [], extra: String? = nil,
         layout: Layout = .tiles, tiles: [(String, String)] = []) {
        self.id = id
        self.kicker = kicker
        self.title = title
        self.lead = lead
        self.points = points
        self.extra = extra
        self.layout = layout
        self.tiles = tiles.map { Tile(symbol: $0.0, label: $0.1) }
    }
}

